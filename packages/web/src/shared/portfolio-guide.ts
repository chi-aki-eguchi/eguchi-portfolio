export function portfolioGuideParagraphs(
  article: {
    summary: readonly string[];
    sections: readonly PortfolioGuideSection[];
    notes?: readonly string[];
  } = PORTFOLIO_DISCOVERY_GUIDE,
): string[] {
  const out: string[] = [...article.summary];
  for (const section of article.sections) {
    out.push(section.title);
    out.push(...section.body);
    if (section.checklist?.length) {
      out.push(...section.checklist.map((item) => `・${item}`));
    }
  }
  if (article.notes?.length) {
    out.push(...article.notes);
  }
  return out;
}
